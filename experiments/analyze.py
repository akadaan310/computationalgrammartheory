"""Analysis of raw results -> experiments/results/SUMMARY.md (tables + fits).

Run after the experiments:  python3 experiments/analyze.py
Empirical fits are descriptive only; they do not establish asymptotic bounds.
"""
from __future__ import annotations

import json
import math
import os

R = os.path.join(os.path.dirname(__file__), "results")


def load(name):
    with open(os.path.join(R, name)) as f:
        return json.load(f)


def linfit(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    b = sxy / sxx
    a = my - b * mx
    ss_res = sum((y - (a + b * x)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys) or 1e-12
    return a, b, 1 - ss_res / ss_tot


def main():
    out = ["# Experimental summary (generated by analyze.py)\n",
           "All costs are counted elementary steps under the cost model stated in each",
           "experiment file; wall-clock seconds are in the JSON files.\n"]

    e = load("exp001.json")
    out += ["## CGT-EXP-001 binary tree navigation (LCA ops/query)\n",
            "| shape | n | height | workload | R1 pointer | R2 heap-arith | R3 address-LCP | R4 Euler+sparse | R4 build ops | R2 density n/2^(h+1) |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r in e["rows"]:
        for wl in ("rand", "deep"):
            r3 = r.get(f"{wl}.R3.lca_ops_per_q")
            out.append(f"| {r['shape']} | {r['n']} | {r['height']} | {wl} | "
                       f"{r[wl + '.R1.lca_ops_per_q']:.1f} | {r[wl + '.R2.lca_ops_per_q']:.1f} | "
                       f"{'infeasible (Θ(n²) chars)' if r3 is None else f'{r3:.1f}'} | "
                       f"{r[wl + '.R4.lca_ops_per_q']:.1f} | {r['R4-euler-sparse.build_ops']} | "+ (f"{r['R2.density']:.3g} |" if r['R2.density'] > 0
                          else f"n·2^-{r['height'] + 1} (underflow) |"))

    e = load("exp002.json")
    out += ["\n## CGT-EXP-002 reachability: search vs closure vs path grammar\n",
            "| family | n | m | P(reach) | BFS ops/q | TC build ops | break-even Q* (ops) | Q* (wall) | TC bits | zlib bits | n²/4 | path-grammar lin firings | nonlin firings | closure pairs |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in e["rows"]:
        out.append(f"| {r['family']} | {r['n']} | {r['m']} | {r['positive_frac']:.2f} | "
                   f"{r['M1.ops_per_q']:.1f} | {r['M2.build_ops']} | {r['breakeven_Q_ops']:.0f} | "
                   f"{r['breakeven_Q_wall']:.0f} | {r['M2.space_bits']} | {r['M2.compressed_bits_zlib']} | "
                   f"{r['n'] ** 2 // 4} | {r.get('M3lin.firings', '–')} | {r.get('M3nonlin.firings', '–')} | "
                   f"{r['M2.closure_pairs']} |")
    fr = [r for r in e["rows"] if r["family"] == "forest"]
    out += ["\nForest interval labels (M4): " + "; ".join(
        f"n={r['n']}: build {r['M4.build_ops']} ops, {r['M4.space_bits']} bits, "
        f"{r['M4.ops_per_q']:.0f} op/q, break-even Q*={r['breakeven_Q_ops_M4']:.0f}" for r in fr)]
    pr = [r for r in e["rows"] if "path_retrieval_ops_per_q" in r]
    out += ["\nPath retrieval given the closure (DAG/forest): " + "; ".join(
        f"{r['family']} n={r['n']}: {r['path_retrieval_ops_per_q']:.1f} ops for mean length "
        f"{r['path_len_mean']:.1f}" for r in pr)]

    e = load("exp003.json")
    out += ["\n## CGT-EXP-003 language-constrained reachability\n",
            "| n | avg deg | L | Q | product states | unconstrained states | ratio | vertices misreported by unconstrained search |",
            "|---|---|---|---|---|---|---|---|"]
    for r in e["rows"]:
        out.append(f"| {r['n']} | {r['avg_deg']} | `{r['L']}` | {r['Q']} | {r['product_states_mean']:.1f} | "
                   f"{r['unconstrained_states_mean']:.1f} | {r['ratio_product_over_unconstrained']:.3f} | "
                   f"{r['misreported_vertices_mean']:.1f} |")
    out += ["\nWalk enumeration (tiny graph, n=12) vs product construction:\n",
            "| L | max walk length | walks explored | status | product states |", "|---|---|---|---|---|"]
    for t in e["tiny"]:
        out.append(f"| `{t['L']}` | {t['max_len']} | {t['walks_explored']} | {t['status']} | {t['product_states']} |")

    e = load("exp004.json")
    out += ["\n## CGT-EXP-004 forests and minimal-DAG grammars\n",
            "| family | n | DAG nodes g | DAG edges | size ratio | access ops/q (explicit = 1) | new rules per relabel | live g after k relabels |",
            "|---|---|---|---|---|---|---|---|"]
    for r in e["rows"]:
        out.append(f"| {r['family']} | {r['n']} | {r['dag_nodes']} | {r['dag_edges']} | "
                   f"{r['compression_ratio']:.4f} | {r['access_ops_per_q']:.1f} | "
                   f"{r['update_new_rules_mean']:.1f} | {r['live_dag_after_updates']} |")

    e = load("exp005.json")
    out += ["\n## CGT-EXP-005 dynamic workloads (total counted ops over 4000 operations)\n",
            "| workload | S1 BFS | S2 lazy rebuild | S3 incremental | S4 memo | cheapest |", "|---|---|---|---|---|---|"]
    for r in e["rows"]:
        c = r["costs"]
        out.append(f"| {r['workload']} | {c['S1_bfs']} | {c['S2_rebuild']} | {c['S3_incremental']} | "
                   f"{c['S4_memo']} | **{r['best']}** |")

    e = load("exp006.json")
    out += ["\n## CGT-EXP-006 solution grammars for CNF (residual-dedup automaton)\n",
            "| family | k | median nodes | log2(nodes)/k |", "|---|---|---|---|"]
    fams = {}
    for r in e["rows"]:
        out.append(f"| {r['family']} | {r['k']} | {r['median_nodes']} | "
                   f"{math.log2(r['median_nodes']) / r['k']:.3f} |")
        fams.setdefault(r["family"], []).append((r["k"], r["median_nodes"]))
    out += ["\nModel comparison on medians (descriptive; k ≤ 28 is far too small to decide asymptotics):\n",
            "| family | exp fit: log2 N = a + b·k (b, R²) | poly fit: log2 N = a + c·log2 k (c, R²) |", "|---|---|---|"]
    for f, pts in fams.items():
        ks = [k for k, _ in pts]; ys = [math.log2(v) for _, v in pts]
        _, b, r2e = linfit(ks, ys)
        _, c, r2p = linfit([math.log2(k) for k in ks], ys)
        out.append(f"| {f} | b={b:.3f}, R²={r2e:.3f} | c={c:.2f}, R²={r2p:.3f} |")

    e = load("exp007.json")
    out += ["\n## CGT-EXP-007 grammar shape: right-linear vs doubling path grammar\n",
            "| family | n | closure pairs | linear firings | = THM-004 formula | linear parallel depth | doubling firings | doubling parallel depth |",
            "|---|---|---|---|---|---|---|---|"]
    for r in e["rows"]:
        out.append(f"| {r['family']} | {r['n']} | {r['closure_pairs']} | {r['linear_firings']} | "
                   f"{'yes' if r['linear_firings'] == r['linear_predicted'] else 'NO'} | "
                   f"{r['linear_parallel_depth']} | {r['doubling_firings']} | {r['doubling_parallel_depth']} |")

    with open(os.path.join(R, "SUMMARY.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
